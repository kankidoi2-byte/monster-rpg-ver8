import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {runtime} from '../tools/balance-audit/runtime.mjs';
const r=runtime({save:s=>s+'\nglobalThis.realSaveGame=saveGame;'});
r.context.console={...console,error(){}};
vm.runInContext(fs.readFileSync(new URL('../js/home-missions.js',import.meta.url),'utf8'),r.context);
r.run(`saveGame=realSaveGame;save=initSave();save.coins=25;saveGame();var resourcePaints=0;updateAppResourceBar=()=>resourcePaints++;renderHome=()=>{throw Error('must not rerender home')};`);
assert.equal(r.run('homeMissionRows().filter(x=>x.state==="ready").length'),0);
assert.equal(r.run('claimHomeMission("prologue_clear")'),false);
r.run('save.prologuePart2.completed=true');
assert.equal(r.run('homeMissionRows()[0].state'),'locked','part2 is not the literal flag');
r.run('save.progress.tutorial.prologueCompleted=true');
assert.equal(r.run('homeMissionRows()[0].state'),'ready','older saves may have the completion flag only in tutorial');
r.run('save.progress.storyFlags.prologueCompleted=false');
assert.equal(r.run('homeMissionRows()[0].state'),'locked','an explicit story flag takes precedence');
r.run('save.progress.storyFlags.prologueCompleted=true;saveGame()');
assert.equal(r.run('claimHomeMission("prologue_clear")'),true);
assert.equal(r.run('save.coins'),525);
assert.equal(r.run('resourcePaints'),1,'coin bar updates without home rerender');
assert.equal(r.run('claimHomeMission("prologue_clear")'),false);
assert.equal(r.run('claimHomeMission("unknown")'),false);
assert.equal(r.run('JSON.parse(localStorage.getItem(SAVE_KEY)).homeMissions.claimedIds[0]'),'prologue_clear');
r.run(`recordHomeMissionAlchemyExecution();saveGame();var before=JSON.stringify(save);var disk=localStorage.getItem(SAVE_KEY);var oldSet=localStorage.setItem;localStorage.setItem=()=>{throw Error('quota')};`);
assert.equal(r.run('claimHomeMission("alchemy_once")'),false);
assert.equal(r.run('JSON.stringify(save)'),r.run('before'),'quota rolls back reward and receipt');
assert.equal(r.run('localStorage.getItem(SAVE_KEY)'),r.run('disk'));
r.run('localStorage.setItem=oldSet');
assert.equal(r.run('claimHomeMission("alchemy_once")'),true);
assert.equal(r.run('save.coins'),1025);
r.run('save=JSON.parse(localStorage.getItem(SAVE_KEY))');
assert.equal(r.run('claimHomeMission("alchemy_once")'),false,'reload retains claim');
assert.equal(r.run(`normalizeHomeMissions(null,{contractor:{recentExp:[{source:'alchemy_success',amount:50}]}}).alchemyCount`),1,'real legacy evidence');
assert.equal(r.run(`normalizeHomeMissions(null,{progress:{tutorial:{alchemyLessonCompleted:true}}}).alchemyCount`),0,'migration-created tutorial flag is not evidence');
assert.equal(r.run(`normalizeHomeMissions({extra:'keep',claimedIds:['future','future'],alchemyCount:3}).extra`),'keep');
assert.equal(r.run(`normalizeHomeMissions({claimedIds:['future','future']}).claimedIds.length`),1);
assert.equal(r.run(`normalizeHomeMissions({alchemyCount:-2}).alchemyCount`),0);
// Repair is additive: unrelated receipts/resources/settings remain unchanged.
r.run(`var legacy=initSave();delete legacy.homeMissions;legacy.coins=731;legacy.items.monster_bone=9;legacy.giftClaimedIds=['existing'];legacy.customFuture={keep:true};legacy.progress.storyFlags.prologueCompleted=true;var flags=JSON.stringify(legacy.progress.storyFlags);repairSave(legacy);`);
assert.equal(r.run('legacy.coins'),731,'repair never grants rewards');
assert.equal(r.run('legacy.items.monster_bone'),9);
assert.equal(r.run('legacy.giftClaimedIds[0]'),'existing');
assert.equal(r.run('legacy.customFuture.keep'),true);
assert.equal(r.run('JSON.stringify(legacy.progress.storyFlags)'),r.run('flags'));
assert.equal(r.run('legacy.homeMissions.claimedIds.length'),0);
assert.equal(r.run('legacy.homeMissions.alchemyCount'),0);
// Exercise actual alchemy finalization, including duplicate plan suppression and failed persistence.
r.run(`save=initSave();save.coins=1000;save.items.monster_bone=10;var oldSaveGame=saveGame;var alchemyNotices=[];
showAlchemyNotice=(...args)=>alchemyNotices.push(args);showAlchemyFailure=()=>{};
var testPlan={selection:{materialIds:['monster_bone'],materialCounts:[1]},coinCost:10,tutorialLesson:false,instance:{uid:'catalyst'},recipe:{},coinOption:{}};
alchemyPlan=()=>testPlan;validateAlchemyPlan=()=>[];rollAlchemySuccess=()=>false;rollAlchemyResultCandidate=()=>({});
createAlchemyResultInstance=()=>({resultMonster:{name:'test',types:[]},resultInstance:{uid:'result'},archetype:null});
var first={selection:testPlan.selection};finalizeAlchemy(first);`);
assert.equal(r.run('save.homeMissions.alchemyCount'),1,'fallback still counts completed execution');
r.run('finalizeAlchemy(first)');
assert.equal(r.run('save.homeMissions.alchemyCount'),1,'same committed plan cannot count twice');
r.run(`var snapshot=JSON.stringify(save);saveGame=()=>false;finalizeAlchemy({selection:testPlan.selection});`);
assert.equal(r.run('JSON.stringify(save)'),r.run('snapshot'),'alchemy failure rolls back resources and count');
console.log('Home missions: claims, legacy evidence, persistence, rollback and alchemy integration passed');

