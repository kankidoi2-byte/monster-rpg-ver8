import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const c=vm.createContext({console});
vm.runInContext(fs.readFileSync(new URL('../js/world-events.js',import.meta.url),'utf8'),c);
const plain=value=>JSON.parse(JSON.stringify(value));
const details={receiptId:'world-victory:1',difficultyId:'hard',mapId:'light_plain'};
const original={futureField:{kept:true},active:{futurePortal:{location:'future'},elysia:null},history:[],riftCycle:0};
const before=JSON.stringify(original);
let state=c.rollWorldEventsAfterVictory(original,details,()=>0);
assert.equal(JSON.stringify(original),before,'transitions must not mutate incoming save');
assert.equal(state.normalVictories,1);
assert.equal(state.futureField.kept,true);
assert.equal(state.active.futurePortal.location,'future');
assert.equal(state.active.elysia.monsterId,'hikari');
assert.equal(state.active.crisis.monsterId,'doom_nemesion');
assert.equal(state.active.starsea.monsterId,'nemesion');
assert.ok(state.active.water_secret&&state.active.golden_land,'all entrances coexist');
assert.equal(state.guides.elysia,false);
assert.equal(state.guides.map_intro,false);
assert.equal(state.guides.crisis,false);
assert.equal(state.guides.rift,false);
assert.equal(state.guides.special_entrance,false);
for(const key of ['elysia','crisis','water_secret','starsea','golden_land'])assert.equal(c.worldEventGuideIsUnread(state,key),true);
assert.equal(c.worldEventGuideIsUnread(state,'rift'),false,'a guide is not pending before its event exists');
const stateBeforeGuide=JSON.stringify(state);
const elysiaGuideSeen=c.markWorldEventGuideSeen(state,'elysia');
assert.equal(JSON.stringify(state),stateBeforeGuide,'acknowledging a guide must not mutate incoming save');
assert.equal(c.worldEventGuideIsUnread(elysiaGuideSeen,'elysia'),false);
assert.ok(elysiaGuideSeen.active.elysia&&elysiaGuideSeen.active.crisis,'acknowledging a guide must not consume events');
const specialGuideSeen=c.markWorldEventGuideSeen(state,'water_secret');
for(const key of ['water_secret','starsea','golden_land'])assert.equal(c.worldEventGuideIsUnread(specialGuideSeen,key),false,'special entrances share one first-time guide');
assert.equal(c.worldEventGuideIsUnread(specialGuideSeen,'crisis'),true,'unrelated guides remain pending');
const duplicate=c.rollWorldEventsAfterVictory(state,details,()=>{throw Error('duplicate drew RNG');});
assert.deepEqual(plain(duplicate),plain(state));
const duplicateOld=c.rollWorldEventsAfterVictory({...state,lastVictoryReceiptNumber:100},details,()=>{throw Error('old result drew RNG');});
assert.equal(duplicateOld.normalVictories,1,'old receipts must remain deduplicated without unlimited history');
for(const outcome of ['loss','escape','reload','unknown'])assert.deepEqual(plain(c.resolveWorldEvent(state,'crisis',outcome)),plain(state));
const defeated=c.resolveWorldEvent(state,'crisis','defeat');
const skipped=c.resolveWorldEvent(state,'crisis','skip');
assert.deepEqual(plain(defeated.active.rift),plain(skipped.active.rift),'skipping must not grant a better rift');
assert.equal(defeated.history.at(-1).handledBy,'player');
assert.equal(skipped.history.at(-1).handledBy,'false_dragons');
assert.equal(defeated.active.rift.monsterIds.length,3);
assert.equal(c.worldEventGuideIsUnread(defeated,'rift'),true);
assert.ok(defeated.active.elysia&&defeated.active.starsea&&defeated.active.golden_land,'resolving crisis preserves unrelated entries');
let rift=c.resolveWorldEvent(defeated,'rift','defeat');
assert.equal(rift.active.rift.monsterId,'false_dragon_beta');
assert.equal(rift.active.rift.monsterIds.length,2);
const activeBefore=JSON.stringify(rift.active.rift);
rift=c.rollWorldEventsAfterVictory(rift,{...details,receiptId:'world-victory:2'},()=>0);
assert.equal(JSON.stringify(rift.active.rift),activeBefore,'new crisis does not replace an existing rift');
rift=c.resolveWorldEvent(rift,'crisis','skip');
assert.equal(rift.active.rift.monsterId,'false_dragon_beta','existing next opponent stays first');
assert.equal(rift.active.rift.monsterIds.length,3,'crisis refills missing opportunity without losing pending ones');
for(let i=0;i<3;i++)rift=c.resolveWorldEvent(rift,'rift','defeat');
assert.equal(rift.active.rift,null,'only all three resolutions close the rift');
assert.deepEqual(plain(c.resolveWorldEvent(rift,'rift','defeat')),plain(rift),'resolved entries cannot resolve twice');
const old=c.normalizeWorldMapState({normalVictories:-3,active:null,processedReceiptIds:'bad',history:{},future:true});
assert.equal(old.normalVictories,0);assert.equal(old.active.crisis,null);assert.equal(old.future,true);
assert.deepEqual(plain(old.guides),{map_intro:false,elysia:false,crisis:false,rift:false,special_entrance:false});
for(const value of [null,[],0,'old'])assert.equal(c.normalizeWorldMapState(value).version,1);
const unknown=c.normalizeWorldMapState({version:8,active:{elysia:{mapId:'light_plain',custom:7},future:{kept:true}}});
assert.equal(unknown.version,8);assert.equal(unknown.active.elysia.custom,7);assert.equal(unknown.active.future.kept,true);
const futureGuide=c.normalizeWorldMapState({guides:{elysia:true,future_guide:'kept'}});
assert.equal(futureGuide.guides.elysia,true);assert.equal(futureGuide.guides.future_guide,'kept');
assert.equal(c.worldEventGuideIsUnread(state,'futurePortal'),false);
assert.deepEqual(plain(c.markWorldEventGuideSeen(state,'futurePortal')),plain(state),'unknown guide keys are ignored');
const easy=c.rollWorldEventsAfterVictory(null,{...details,difficultyId:'easy'},()=>0);
assert.ok(Object.values(easy.active).every(v=>v===null),'Easy creates no dangerous event');
const notLight=c.rollWorldEventsAfterVictory(null,{...details,mapId:'grassland'},()=>0);
assert.equal(notLight.active.elysia,null,'goddess descends only after exploring Light Plain');
const failed=c.rollWorldEventsAfterVictory(null,details,()=>.99);
assert.ok(Object.values(failed.active).every(v=>v===null));
assert.equal(c.rollWorldEventsAfterVictory(null,{...details,receiptId:''},()=>0).normalVictories,0);
let custom=c.rollWorldEventsAfterVictory(null,{...details,receiptId:'custom'},()=>.99);
assert.equal(c.rollWorldEventsAfterVictory(custom,{...details,receiptId:'custom'},()=>0).normalVictories,1);
const damaged={active:{
  elysia:{mapId:'bad',monsterId:'doom_nemesion',custom:'kept'},
  crisis:{monsterId:'not_a_monster',futureFlag:2},
  starsea:{mapId:'world_between',monsterId:'false_dragon_alfa'},
  water_secret:{mapId:'bad',monsterId:'hikari',custom:3},
  golden_land:{monsterId:'elixion'},
  rift:{mapId:'grassland',monsterId:'bad',monsterIds:['false_dragon_gamma','bad','false_dragon_gamma','false_dragon_beta'],custom:4},
  nextEra:{mapId:'future',monsterId:'future_monster'}
},history:Array.from({length:45},(_,i)=>({i,unknown:true}))};
const damagedBefore=JSON.stringify(damaged);
const repaired=c.normalizeWorldMapState(damaged);
assert.equal(JSON.stringify(damaged),damagedBefore,'repair must not mutate damaged saves');
assert.equal(repaired.active.elysia.mapId,'light_plain');
assert.equal(repaired.active.elysia.monsterId,'hikari');assert.equal(repaired.active.elysia.custom,'kept');
assert.equal(repaired.active.crisis.mapId,'starsea');assert.equal(repaired.active.crisis.monsterId,'doom_nemesion');
assert.equal(repaired.active.crisis.futureFlag,2);
assert.equal(repaired.active.starsea.monsterId,'nemesion');
assert.equal(repaired.active.water_secret.mapId,'water_secret');assert.equal(repaired.active.water_secret.monsterId,undefined);
assert.equal(repaired.active.water_secret.custom,3);assert.equal(repaired.active.golden_land.monsterId,undefined);
assert.equal(repaired.active.golden_land.mapId,'golden_land');
assert.equal(repaired.active.rift.mapId,'world_between');assert.equal(repaired.active.rift.monsterId,'false_dragon_gamma');
assert.deepEqual(plain(repaired.active.rift.monsterIds),['false_dragon_gamma','false_dragon_beta']);
assert.equal(repaired.active.rift.custom,4);assert.equal(repaired.active.nextEra.monsterId,'future_monster');
assert.equal(repaired.history.length,30);assert.equal(repaired.history[0].i,15);assert.equal(repaired.history[0].unknown,true);
assert.deepEqual(plain(c.normalizeWorldMapState(repaired)),plain(repaired),'normalization is idempotent');
const emptyRift=c.normalizeWorldMapState({active:{rift:{monsterId:'bad',monsterIds:[null],futureField:true}}});
assert.equal(emptyRift.active.rift.monsterIds.length,3);assert.equal(emptyRift.active.rift.futureField,true);
const currentRift=c.normalizeWorldMapState({active:{rift:{monsterId:'false_dragon_beta',monsterIds:['false_dragon_gamma']}}});
assert.deepEqual(plain(currentRift.active.rift.monsterIds),['false_dragon_beta','false_dragon_gamma']);
console.log('World events passed: additive migration, independent persistence, one-time guides, receipt deduplication, Elysia/crisis, fair rift queues, loss/escape, and legacy values.');
