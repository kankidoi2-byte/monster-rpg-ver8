import assert from 'node:assert/strict';
import fs from 'node:fs';
import {runtime} from '../tools/balance-audit/runtime.mjs';
const r=runtime();
r.run(`save=initSave();selectedMap=MAPS.find(m=>m.id==='grassland');
activeHuntRequest=createHuntRequest(selectedMap,by('granbeat'),'d5',[],{randomFn:()=>0});
var first=createMultiEnemy(by(activeHuntRequest.enemyId),'enemy_a');
var second=createMultiEnemy(by('granbeat'),'enemy_b');`);
assert.equal(r.run('activeHuntRequest.overtier'),'nushi');
assert.equal(r.run('first.level'),61);
assert.equal(r.run('first.maxHp'),r.run('activeHuntRequest.enemyHp'));
assert.equal(r.run('first.maxHp'),r.run('maxHp(first.mon,61)*3'));
assert.equal(r.run('first.attackMultiplier'),1.8);
assert.equal(r.run('second.attackMultiplier'),1);
assert.equal(r.run('first.rewardMultiplier'),7.2);
assert.equal(r.run('second.rewardMultiplier'),2.4);
assert.ok(r.run('second.level>=46&&second.level<=60'));
assert.equal(r.run('second.maxHp'),r.run('maxHp(second.mon,second.level)'));
assert.equal(r.run("gBlessHuntReward(10,false,'coins',null,second.rewardMultiplier)"),24);
assert.equal(r.run("gBlessHuntReward(10,false,'coins',null,first.rewardMultiplier)"),72);
r.run('var bless={baseExp:0,baseCoins:0};');
assert.equal(r.run("gBlessHuntReward(10,false,'coins',bless,second.rewardMultiplier)"),48);
assert.equal(r.run('bless.baseCoins'),24);
assert.equal(r.run('battleOvertierLabel()'),'ヌシ');
assert.match(r.run('battleOvertierLog()'),/ヌシ/);
// A pending invasion retains the injured primary, not a fresh draw or full heal.
r.run(`enemy=first.mon;eHp=first.maxHp-100;eAtk=1.2;var existing=createExistingMultiEnemy();`);
assert.equal(r.run('existing.level'),61);
assert.equal(r.run('existing.hp'),r.run('first.maxHp-100'));
assert.equal(r.run('existing.attackMultiplier'),1.8);
assert.equal(r.run('existing.rewardMultiplier'),7.2);
r.run(`activeHuntRequest=createHuntRequest(selectedMap,by('slime'),'d1',[],{randomFn:()=>0});
first=createMultiEnemy(by(activeHuntRequest.enemyId),'enemy_a');second=createMultiEnemy(by('slime'),'enemy_b');`);
assert.equal(r.run('activeHuntRequest.overtier'),'stronger');
assert.equal(r.run('first.level'),6);
assert.ok(r.run('second.level>=1&&second.level<=6'));
assert.equal(r.run('first.rewardMultiplier'),1.05);
assert.equal(r.run('second.rewardMultiplier'),.7);
assert.equal(r.run('battleOvertierLabel()'),'格上');
assert.equal(r.run('battleOvertierLabel({})'),'');
// The legacy fallback remains private before departure too: only the base
// tier range/reward is displayed, never the hidden encounter stats or name.
